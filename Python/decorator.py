# DECORATOR : A function that extends the behavior of another function
#             w/o modifying the base function
#             Pass the base function as an argument to the decorator
# A decorator is a function that adds or modifies the behavior of another function without changing its original code.
# Think of it like adding toppings to a pizza 🍕:
#    Pizza = Original function
#    Cheese = Decorator
#    Olives = Another decorator
# The pizza is still the same, but its behavior (or appearance) has been enhanced.

